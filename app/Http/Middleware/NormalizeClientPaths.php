<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/*
    NormalizeClientPaths
     - Roblox clients and RCC request things like /Game/PlaceLauncher.ashx and /Asset/?id=1,
       with whatever capitalisation that build uses, but Laravel matches routes case-sensitively.
       On the client hosts (www. and assetgame.) the path is lowercased before routing, and the
       client routes are all defined in lowercase. Query strings are left alone.
     - /api/gameserver/... is skipped: those URLs carry job IDs and are generated by the site itself.
*/
class NormalizeClientPaths
{
    public function handle(Request $request, Closure $next): Response
    {
        $domain = config('finobe.domain');
        $host = strtolower($request->getHost());
        $path = $request->getPathInfo();
        $lower = strtolower($path);

        // http://roblox.com/asset/?id=... (no www) in places becomes finobe.wtf/asset, which is the website:
        // send asset/thumbnail requests to the client host
        if ($host === $domain && (in_array($lower, ['/asset', '/asset/'], true)
                || in_array($lower, ['/thumbs/asset.ashx', '/asset-thumbnail/image', '/thumbs/avatar.ashx', '/thumbs/avatar-headshot.ashx'], true))) {
            $query = $request->server->get('QUERY_STRING');
            return redirect()->away($request->getScheme() . "://www.{$domain}{$lower}" . ($query ? '?' . $query : ''));
        }

        if ($lower !== $path
            && in_array($host, ["www.{$domain}", "assetgame.{$domain}"], true)
            && !str_starts_with($lower, '/api/gameserver/')) {
            $server = $request->server->all();
            $query = $request->server->get('QUERY_STRING');
            $server['REQUEST_URI'] = $lower . ($query !== null && $query !== '' ? '?' . $query : '');

            $request = $request->duplicate(null, null, null, null, null, $server);
            app()->instance('request', $request);
        }

        return $next($request);
    }
}
